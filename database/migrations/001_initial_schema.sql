CREATE TABLE IF NOT EXISTS public.temas (
    temas_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "numTema" integer,
    "typeTema" text,
    "tieneReformaPendiente" boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public."temasVueltas" (
    vuelta_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temas_id bigint NOT NULL REFERENCES public.temas (temas_id) ON DELETE CASCADE,
    "fechaVuelta" date NOT NULL,
    "numVuelta" integer NOT NULL CHECK ("numVuelta" BETWEEN 1 AND 32767)
);

CREATE TABLE IF NOT EXISTS public."temasCantes" (
    cante_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temas_id bigint NOT NULL REFERENCES public.temas (temas_id) ON DELETE CASCADE,
    "numCante" integer NOT NULL CHECK ("numCante" BETWEEN 1 AND 32767),
    "tiempoCante" smallint NOT NULL DEFAULT 0 CHECK ("tiempoCante" >= 0),
    "observacionesCante" text NOT NULL DEFAULT ''
);

ALTER TABLE public.temas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."temasVueltas" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."temasCantes" ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS temas_authenticated_select ON public.temas;
CREATE POLICY temas_authenticated_select ON public.temas
    FOR SELECT TO authenticated
    USING (auth.user_id() IS NOT NULL);

DROP POLICY IF EXISTS temas_authenticated_update ON public.temas;
CREATE POLICY temas_authenticated_update ON public.temas
    FOR UPDATE TO authenticated
    USING (auth.user_id() IS NOT NULL)
    WITH CHECK (auth.user_id() IS NOT NULL);

DROP POLICY IF EXISTS temas_vueltas_authenticated_all ON public."temasVueltas";
CREATE POLICY temas_vueltas_authenticated_all ON public."temasVueltas"
    FOR ALL TO authenticated
    USING (auth.user_id() IS NOT NULL)
    WITH CHECK (auth.user_id() IS NOT NULL);

DROP POLICY IF EXISTS temas_cantes_authenticated_all ON public."temasCantes";
CREATE POLICY temas_cantes_authenticated_all ON public."temasCantes"
    FOR ALL TO authenticated
    USING (auth.user_id() IS NOT NULL)
    WITH CHECK (auth.user_id() IS NOT NULL);

GRANT USAGE ON SCHEMA public TO authenticated;
GRANT SELECT, UPDATE ON public.temas TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public."temasVueltas", public."temasCantes" TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
